USE WAREHOUSE RETAIL_WH;
USE DATABASE RETAIL_CLARK;
USE SCHEMA MART;
-- Référentiels fournis valides ; contrôles d'unicité dans 04_checks.sql.
CREATE OR REPLACE VIEW DIM_PRODUIT AS
 SELECT DISTINCT PRODUIT_ID,LIBELLE,CATEGORIE,TO_DECIMAL(COUT_ACHAT,12,2) COUT_ACHAT FROM RAW.PRODUITS;
CREATE OR REPLACE VIEW DIM_MAGASIN AS SELECT DISTINCT * FROM RAW.MAGASINS;
CREATE OR REPLACE VIEW DQ.V_VALIDATION AS
 SELECT v.*,
 CASE WHEN TRY_TO_DATE(v.DATE_VENTE,'YYYY-MM-DD') IS NULL THEN 'DATE_INVALIDE'
 WHEN p.PRODUIT_ID IS NULL THEN 'PRODUIT_INCONNU'
 WHEN m.MAGASIN_ID IS NULL THEN 'MAGASIN_INCONNU'
 WHEN TRY_TO_DECIMAL(v.QUANTITE,12,3) IS NULL OR TRY_TO_DECIMAL(v.QUANTITE,12,3)<1
   OR MOD(TRY_TO_DECIMAL(v.QUANTITE,12,3),1)<>0 THEN 'QUANTITE_INVALIDE'
 WHEN TRY_TO_DECIMAL(v.PRIX_UNITAIRE,12,2) IS NULL OR TRY_TO_DECIMAL(v.PRIX_UNITAIRE,12,2)<0 THEN 'PRIX_INVALIDE'
 WHEN TRY_TO_DECIMAL(v.REMISE,8,4) IS NULL OR TRY_TO_DECIMAL(v.REMISE,8,4) NOT BETWEEN 0 AND 1 THEN 'REMISE_INVALIDE'
 ELSE NULL END MOTIF
 FROM RAW.VENTES v LEFT JOIN MART.DIM_PRODUIT p ON v.PRODUIT_ID=p.PRODUIT_ID
 LEFT JOIN MART.DIM_MAGASIN m ON v.MAGASIN_ID=m.MAGASIN_ID;
CREATE OR REPLACE VIEW DQ.V_REJETS AS SELECT * FROM DQ.V_VALIDATION WHERE MOTIF IS NOT NULL;
CREATE OR REPLACE VIEW DQ.V_DOUBLONS AS
 SELECT * FROM DQ.V_VALIDATION WHERE MOTIF IS NULL
 QUALIFY ROW_NUMBER() OVER(PARTITION BY LIGNE_ID ORDER BY DATE_VENTE,COMMANDE_ID,PRODUIT_ID)>1;
CREATE OR REPLACE VIEW V_VENTES_VALIDES AS
 SELECT LIGNE_ID,COMMANDE_ID,TO_DATE(DATE_VENTE,'YYYY-MM-DD') DATE_VENTE,MAGASIN_ID,PRODUIT_ID,
 TO_NUMBER(QUANTITE) QUANTITE,TO_DECIMAL(PRIX_UNITAIRE,12,2) PRIX_UNITAIRE,TO_DECIMAL(REMISE,8,4) REMISE
 FROM DQ.V_VALIDATION WHERE MOTIF IS NULL
 QUALIFY ROW_NUMBER() OVER(PARTITION BY LIGNE_ID ORDER BY DATE_VENTE,COMMANDE_ID,PRODUIT_ID)=1;
CREATE TABLE IF NOT EXISTS FACT_VENTE (LIGNE_ID VARCHAR,COMMANDE_ID VARCHAR,DATE_VENTE DATE,
 MAGASIN_ID VARCHAR,PRODUIT_ID VARCHAR,QUANTITE NUMBER,PRIX_UNITAIRE NUMBER(12,2),REMISE NUMBER(8,4));
-- Upsert relançable. Les CSV inclus sont un lot initial immuable ; pas de gestion de suppression source.
MERGE INTO FACT_VENTE t USING V_VENTES_VALIDES s ON t.LIGNE_ID=s.LIGNE_ID
 WHEN MATCHED THEN UPDATE SET t.COMMANDE_ID=s.COMMANDE_ID,t.DATE_VENTE=s.DATE_VENTE,
 t.MAGASIN_ID=s.MAGASIN_ID,t.PRODUIT_ID=s.PRODUIT_ID,t.QUANTITE=s.QUANTITE,
 t.PRIX_UNITAIRE=s.PRIX_UNITAIRE,t.REMISE=s.REMISE
 WHEN NOT MATCHED THEN INSERT (LIGNE_ID,COMMANDE_ID,DATE_VENTE,MAGASIN_ID,PRODUIT_ID,QUANTITE,PRIX_UNITAIRE,REMISE)
 VALUES(s.LIGNE_ID,s.COMMANDE_ID,s.DATE_VENTE,s.MAGASIN_ID,s.PRODUIT_ID,s.QUANTITE,s.PRIX_UNITAIRE,s.REMISE);
CREATE OR REPLACE VIEW DIM_DATE AS SELECT DISTINCT DATE_VENTE,DATE_TRUNC('MONTH',DATE_VENTE)::DATE MOIS,
 YEAR(DATE_VENTE) ANNEE,MONTH(DATE_VENTE) NUM_MOIS FROM FACT_VENTE;
CREATE OR REPLACE VIEW V_VENTES_DETAIL AS SELECT f.*,p.LIBELLE,p.CATEGORIE,p.COUT_ACHAT,m.VILLE,m.REGION,
 ROUND(f.QUANTITE*f.PRIX_UNITAIRE*(1-f.REMISE),2) CA_NET,
 ROUND(ROUND(f.QUANTITE*f.PRIX_UNITAIRE*(1-f.REMISE),2)-f.QUANTITE*p.COUT_ACHAT,2) MARGE_ESTIMEE,
 DATE_TRUNC('MONTH',f.DATE_VENTE)::DATE MOIS
 FROM FACT_VENTE f JOIN DIM_PRODUIT p ON f.PRODUIT_ID=p.PRODUIT_ID JOIN DIM_MAGASIN m ON f.MAGASIN_ID=m.MAGASIN_ID;
CREATE OR REPLACE VIEW FACT_STOCK AS SELECT DISTINCT TO_DATE(DATE_STOCK) DATE_STOCK,MAGASIN_ID,
 PRODUIT_ID,TO_NUMBER(STOCK_DISPONIBLE) STOCK_DISPONIBLE FROM RAW.STOCKS;
CREATE OR REPLACE VIEW FACT_OBJECTIF AS SELECT DISTINCT TO_DATE(MOIS) MOIS,MAGASIN_ID,
 TO_DECIMAL(OBJECTIF_CA,12,2) OBJECTIF_CA FROM RAW.OBJECTIFS;
CREATE OR REPLACE VIEW V_STOCKS_DETAIL AS SELECT s.*,p.LIBELLE,p.CATEGORIE,p.COUT_ACHAT,m.VILLE,m.REGION
 FROM FACT_STOCK s JOIN DIM_PRODUIT p ON s.PRODUIT_ID=p.PRODUIT_ID JOIN DIM_MAGASIN m ON s.MAGASIN_ID=m.MAGASIN_ID;
CREATE OR REPLACE VIEW V_OBJECTIFS_DETAIL AS SELECT o.*,m.VILLE,m.REGION FROM FACT_OBJECTIF o JOIN DIM_MAGASIN m ON o.MAGASIN_ID=m.MAGASIN_ID;
-- Agréger les ventes AVANT de joindre les objectifs : évite de multiplier les objectifs par les lignes de vente.
CREATE OR REPLACE VIEW KPI_MENSUELS AS
 WITH ventes AS (SELECT MOIS,MAGASIN_ID,SUM(CA_NET) CA_NET,SUM(MARGE_ESTIMEE) MARGE_ESTIMEE,
 COUNT(DISTINCT COMMANDE_ID) COMMANDES FROM V_VENTES_DETAIL GROUP BY MOIS,MAGASIN_ID)
 SELECT o.MOIS,o.MAGASIN_ID,COALESCE(v.CA_NET,0) CA_NET,COALESCE(v.MARGE_ESTIMEE,0) MARGE_ESTIMEE,
 COALESCE(v.COMMANDES,0) COMMANDES,o.OBJECTIF_CA,
 COALESCE(v.CA_NET,0)/NULLIF(o.OBJECTIF_CA,0) ATTEINTE_OBJECTIF
 FROM FACT_OBJECTIF o LEFT JOIN ventes v ON o.MOIS=v.MOIS AND o.MAGASIN_ID=v.MAGASIN_ID;
INSERT INTO DQ.CHARGEMENTS(EXECUTION_ID,SOURCE,NB_BRUT,NB_VALIDES,NB_REJETS,NB_DOUBLONS)
 SELECT UUID_STRING(),'CSV initiaux',(SELECT COUNT(*) FROM RAW.VENTES),
 (SELECT COUNT(*) FROM FACT_VENTE),(SELECT COUNT(*) FROM DQ.V_REJETS),(SELECT COUNT(*) FROM DQ.V_DOUBLONS);
