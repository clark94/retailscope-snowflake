-- Exécuter avec un rôle autorisé à créer base, schémas et warehouse (SYSADMIN en essai personnel).
CREATE WAREHOUSE IF NOT EXISTS RETAIL_WH WAREHOUSE_SIZE='XSMALL'
  AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE;
USE WAREHOUSE RETAIL_WH;
CREATE DATABASE IF NOT EXISTS RETAIL_CLARK;
USE DATABASE RETAIL_CLARK;
CREATE SCHEMA IF NOT EXISTS RAW;
CREATE SCHEMA IF NOT EXISTS MART;
CREATE SCHEMA IF NOT EXISTS DQ;
USE SCHEMA RAW;
CREATE FILE FORMAT IF NOT EXISTS FF_CSV TYPE=CSV FIELD_DELIMITER=','
  SKIP_HEADER=1 FIELD_OPTIONALLY_ENCLOSED_BY='"' ENCODING='UTF8'
  EMPTY_FIELD_AS_NULL=TRUE NULL_IF=('') ERROR_ON_COLUMN_COUNT_MISMATCH=TRUE;
CREATE STAGE IF NOT EXISTS CSV_STAGE FILE_FORMAT=FF_CSV;
CREATE TABLE IF NOT EXISTS PRODUITS (PRODUIT_ID VARCHAR, LIBELLE VARCHAR, CATEGORIE VARCHAR, COUT_ACHAT VARCHAR);
CREATE TABLE IF NOT EXISTS MAGASINS (MAGASIN_ID VARCHAR, VILLE VARCHAR, REGION VARCHAR);
CREATE TABLE IF NOT EXISTS VENTES (LIGNE_ID VARCHAR, COMMANDE_ID VARCHAR, DATE_VENTE VARCHAR,
  MAGASIN_ID VARCHAR, PRODUIT_ID VARCHAR, QUANTITE VARCHAR, PRIX_UNITAIRE VARCHAR, REMISE VARCHAR);
CREATE TABLE IF NOT EXISTS STOCKS (DATE_STOCK VARCHAR, MAGASIN_ID VARCHAR, PRODUIT_ID VARCHAR, STOCK_DISPONIBLE VARCHAR);
CREATE TABLE IF NOT EXISTS OBJECTIFS (MOIS VARCHAR, MAGASIN_ID VARCHAR, OBJECTIF_CA VARCHAR);
CREATE TABLE IF NOT EXISTS DQ.CHARGEMENTS (EXECUTION_ID VARCHAR, HORODATAGE TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  SOURCE VARCHAR, NB_BRUT NUMBER, NB_VALIDES NUMBER, NB_REJETS NUMBER, NB_DOUBLONS NUMBER);
