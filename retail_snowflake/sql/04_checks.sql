USE WAREHOUSE RETAIL_WH;
USE DATABASE RETAIL_CLARK;
-- Lot fourni : 6016 brutes = 6000 valides + 6 rejets + 10 doublons.
SELECT (SELECT COUNT(*) FROM RAW.VENTES) BRUTES,
 (SELECT COUNT(*) FROM MART.FACT_VENTE) VALIDES,
 (SELECT COUNT(*) FROM DQ.V_REJETS) REJETS,
 (SELECT COUNT(*) FROM DQ.V_DOUBLONS) DOUBLONS;
SELECT MOTIF,COUNT(*) N FROM DQ.V_REJETS GROUP BY MOTIF;
-- Les quatre requêtes suivantes doivent être vides.
SELECT LIGNE_ID,COUNT(*) FROM MART.FACT_VENTE GROUP BY LIGNE_ID HAVING COUNT(*)>1;
SELECT PRODUIT_ID,COUNT(*) FROM MART.DIM_PRODUIT GROUP BY PRODUIT_ID HAVING COUNT(*)>1;
SELECT DATE_STOCK,MAGASIN_ID,PRODUIT_ID,COUNT(*) FROM MART.FACT_STOCK GROUP BY ALL HAVING COUNT(*)>1;
SELECT MOIS,MAGASIN_ID,COUNT(*) FROM MART.FACT_OBJECTIF GROUP BY ALL HAVING COUNT(*)>1;
SELECT ROUND(SUM(CA_NET),2) CA_NET,ROUND(SUM(MARGE_ESTIMEE),2) MARGE_ESTIMEE,
 COUNT(DISTINCT COMMANDE_ID) COMMANDES FROM MART.V_VENTES_DETAIL;
SELECT * FROM MART.KPI_MENSUELS ORDER BY MOIS,MAGASIN_ID;
SELECT * FROM DQ.CHARGEMENTS ORDER BY HORODATAGE DESC;
